/**
 * Deterministic Tableau Source Validator
 *
 * This script validates that the Tableau data source ingestion is deterministic
 * and correct before QA/build stages.
 *
 * Checks performed:
 * 1. CSV file exists and is readable
 * 2. BOM handling is correct
 * 3. Headers are parsed correctly
 * 4. All required fields are present
 * 5. Date parsing produces valid dates (no epoch)
 * 6. Number parsing produces valid numbers (no NaN)
 * 7. Measures have non-zero values (no all-zero charts)
 * 8. No preamble rows interfere with parsing
 */

const fs = require('fs');
const path = require('path');

const DATA_DIR = './public/data';
const EXPECTED_CSV_FILE = 'πé¡πââπâêπé½πââπâê.csv';
const SCHEMA_FILE = '.tableau-schema.json';

// Expected CSV source fields (excluding runtime-calculated Tableau fields)
const EXPECTED_FIELDS = [
  '投稿日時',
  '媒体',
  'ユーザプロフィールURL',
  '投稿URL/キャプチャー',
  '投稿内容',
  'コメント数',
  'リツイート数',
  'いいね数',
  '検索ワード'
];

const MEASURE_FIELDS = ['コメント数', 'リツイート数', 'いいね数'];

// Runtime-calculated Tableau fields (generated by dataService, not in CSV)
const RUNTIME_CALCULATED_FIELDS = [
  'Number of Records',
  'Calculation_269090137308614656',
  'Calculation_269090137310105601',
  'Calculation_269090137311887363'
];

console.log('╔══════════════════════════════════════════════════════════════════╗');
console.log('║   Deterministic Tableau Source Validator                        ║');
console.log('╚══════════════════════════════════════════════════════════════════╝\n');

let exitCode = 0;

// 1. Check CSV file exists
console.log('📋 Check 1: CSV file exists');
const csvPath = path.join(DATA_DIR, EXPECTED_CSV_FILE);
if (!fs.existsSync(csvPath)) {
  console.error(`   ❌ CSV file not found: ${csvPath}`);
  exitCode = 1;
} else {
  const stats = fs.statSync(csvPath);
  console.log(`   ✅ CSV file found (${stats.size} bytes)`);
}

if (exitCode === 1) {
  console.error('\n❌ Validator failed: CSV file missing');
  process.exit(1);
}

// 2.5. Check for schema file
console.log('\n📋 Check 2.5: Schema file validation');
const schemaPath = path.join(DATA_DIR, SCHEMA_FILE);
if (fs.existsSync(schemaPath)) {
  try {
    const schema = JSON.parse(fs.readFileSync(schemaPath, 'utf8'));
    console.log('   ✅ Schema file found');
    console.log(`   ℹ️  Schema version: ${schema.schema_version || 'unknown'}`);
    console.log(`   ℹ️  Runtime-calculated fields: ${RUNTIME_CALCULATED_FIELDS.length}`);
    console.log('   ℹ️  These fields are generated by dataService.ts at runtime:');
    RUNTIME_CALCULATED_FIELDS.forEach(field => {
      console.log(`      - ${field}`);
    });
  } catch (err) {
    console.warn('   ⚠️  Schema file found but could not be parsed:', err.message);
  }
} else {
  console.log('   ℹ️  No schema file found (optional)');
}


// 2. Check for BOM
console.log('\n🔍 Check 2: BOM detection and handling');
const csvBuffer = fs.readFileSync(csvPath);
const hasBOM = csvBuffer[0] === 0xEF && csvBuffer[1] === 0xBB && csvBuffer[2] === 0xBF;
console.log(`   ${hasBOM ? '✅' : '⚠️'}  BOM detected: ${hasBOM}`);

if (hasBOM) {
  console.log('   ✅ BOM will be removed by dataService.ts');
}

// 3. Check for preamble rows
console.log('\n📄 Check 3: Preamble row detection');
const csvText = fs.readFileSync(csvPath, 'utf8');
const lines = csvText.split('\n');
const firstNonEmptyLine = lines.find(line => line.trim().length > 0);

if (firstNonEmptyLine) {
  const firstLineCleaned = firstNonEmptyLine.replace(/^\uFEFF/, '').trim();
  const looksLikeHeader = EXPECTED_FIELDS.some(field => firstLineCleaned.includes(field));

  if (looksLikeHeader) {
    console.log('   ✅ First line contains expected header fields');
    console.log('   ✅ No preamble rows detected');
  } else {
    console.log('   ⚠️  First line may not be a header');
    console.log('   Content:', firstLineCleaned.substring(0, 100));
  }
}

// 4. Parse and validate headers
console.log('\n🏷️  Check 4: Header validation');
console.log('   ℹ️  Runtime-calculated fields are NOT expected in CSV:');
console.log('      These are added by dataService.ts during load');

const Papa = require('papaparse');

const csvWithoutBOM = hasBOM ? csvText.slice(1) : csvText;
const parseResult = Papa.parse(csvWithoutBOM, {
  header: true,
  skipEmptyLines: true,
  transformHeader: (header) => header.replace(/^"|"$/g, '').trim(),
  preview: 100 // Only parse first 100 rows for validation
});

const actualHeaders = Object.keys(parseResult.data[0] || {});
const missingHeaders = EXPECTED_FIELDS.filter(h => !actualHeaders.includes(h));
const extraHeaders = actualHeaders.filter(h => !EXPECTED_FIELDS.includes(h));

console.log(`   Expected headers: ${EXPECTED_FIELDS.length}`);
console.log(`   Actual headers: ${actualHeaders.length}`);

if (missingHeaders.length > 0) {
  console.log(`   ❌ Missing headers: ${missingHeaders.join(', ')}`);
  exitCode = 1;
} else {
  console.log('   ✅ All expected headers present');
}

if (extraHeaders.length > 0) {
  console.log(`   ℹ️  Extra headers: ${extraHeaders.join(', ')}`);
}

// 5. Validate field parsing
console.log('\n🔧 Check 5: Field parsing validation');

function parseDate(dateStr) {
  if (!dateStr || typeof dateStr !== 'string') return null;
  const cleaned = dateStr.replace(/^"|"$/g, '').trim();
  if (!cleaned) return null;

  const parts = cleaned.split('/');
  if (parts.length === 3) {
    const year = parseInt(parts[0], 10);
    const month = parseInt(parts[1], 10) - 1;
    const day = parseInt(parts[2], 10);
    if (!isNaN(year) && !isNaN(month) && !isNaN(day)) {
      const date = new Date(year, month, day);
      if (date.getFullYear() === year && date.getMonth() === month && date.getDate() === day) {
        return date;
      }
    }
  }
  const date = new Date(cleaned);
  return isNaN(date.getTime()) ? null : date;
}

function parseNumber(value) {
  if (typeof value === 'number') return isNaN(value) ? null : value;
  if (!value) return 0;
  const strValue = String(value).replace(/^"|"$/g, '').trim();
  if (!strValue) return 0;
  const parsed = parseFloat(strValue);
  return isNaN(parsed) ? null : parsed;
}

const validation = {
  dates: { valid: 0, invalid: 0, epoch: 0 },
  numbers: { valid: 0, invalid: 0, nan: 0 },
  strings: { valid: 0, empty: 0 }
};

parseResult.data.forEach((row, idx) => {
  // Validate dates
  const dateStr = row['投稿日時'];
  const date = parseDate(dateStr);
  if (date && !isNaN(date.getTime())) {
    validation.dates.valid++;
    if (date.getFullYear() === 1970 && date.getMonth() === 0 && date.getDate() === 1) {
      validation.dates.epoch++;
    }
  } else {
    validation.dates.invalid++;
  }

  // Validate numbers
  MEASURE_FIELDS.forEach(field => {
    const num = parseNumber(row[field]);
    if (num !== null && !isNaN(num) && num >= 0) {
      validation.numbers.valid++;
    } else {
      validation.numbers.invalid++;
      if (isNaN(num)) validation.numbers.nan++;
    }
  });

  // Validate strings
  ['媒体', 'ユーザプロフィールURL', '投稿内容', '検索ワード'].forEach(field => {
    const val = row[field];
    if (val && val.trim()) {
      validation.strings.valid++;
    } else {
      validation.strings.empty++;
    }
  });
});

console.log('   Dates:');
console.log(`     Valid: ${validation.dates.valid}`);
console.log(`     Invalid: ${validation.dates.invalid}`);
if (validation.dates.epoch > 0) {
  console.log(`     ❌ Epoch dates: ${validation.dates.epoch}`);
  exitCode = 1;
} else {
  console.log('     ✅ No epoch dates');
}

console.log('   Numbers:');
console.log(`     Valid: ${validation.numbers.valid}`);
console.log(`     Invalid: ${validation.numbers.invalid}`);
if (validation.numbers.nan > 0) {
  console.log(`     ❌ NaN values: ${validation.numbers.nan}`);
  exitCode = 1;
} else {
  console.log('     ✅ No NaN values');
}

console.log('   Strings:');
console.log(`     Non-empty: ${validation.strings.valid}`);
console.log(`     Empty: ${validation.strings.empty}`);

// 6. Check for all-zero measures
console.log('\n📊 Check 6: Measure value distribution');

const measureStats = {};
MEASURE_FIELDS.forEach(field => {
  const values = parseResult.data.map(row => parseNumber(row[field]) || 0);
  const sum = values.reduce((a, b) => a + b, 0);
  const nonZero = values.filter(v => v > 0).length;
  const allZero = values.every(v => v === 0);

  measureStats[field] = { sum, nonZero, allZero };

  if (allZero) {
    console.log(`   ❌ ${field}: All zeros (sum=0, nonZero=0)`);
    exitCode = 1;
  } else {
    console.log(`   ✅ ${field}: sum=${sum}, nonZero=${nonZero}`);
  }
});

// Summary
console.log('\n╔══════════════════════════════════════════════════════════════════╗');
if (exitCode === 0) {
  console.log('║   ✅ All checks passed - Data ingestion is deterministic       ║');
  console.log('║                                                                ║');
  console.log('║   Tableau Calculated Fields:                                   ║');
  console.log('║   ✓ Runtime fields generated by dataService.ts                 ║');
  console.log('║   ✓ Source CSV contains only raw data fields                   ║');
} else {
  console.log('║   ❌ Some checks failed - Review errors above                   ║');
}
console.log('╚══════════════════════════════════════════════════════════════════╝\n');

process.exit(exitCode);
